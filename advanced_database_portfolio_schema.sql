CREATE TABLE IF NOT EXISTS public.transfer_processor (
    id bigint NOT NULL,
    currency_fk bigint,
    name_enquiry_url VARCHAR(255),
    processor_code VARCHAR(255),
    processor_name VARCHAR(255),
    processor_status VARCHAR(255),
    skip_name_enquiry boolean,
